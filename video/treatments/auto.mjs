// A sensible default treatment for any analysed song, built from motion.json alone:
// each section gets a scene by its role, palettes follow the tonic, cuts and key changes get
// transitions. Hand-written treatments (like numb-roomie.json) override all of this.

const BASE = {
  night: { sky0: '#05060f', sky1: '#110f26', horizon: '#1a1638', fog: '#3b2a4a', amber: '#ffb25e', rose: '#ff8c7a', star: '#cfd8ff', ground: '#07070d' },
  screens: { sky0: '#04070d', back: '#123038', backHi: '#7fb8c4', screen: '#cfefff', figure: '#000000', frost: '#bfd4dc', warm: '#ffb25e', ground: '#05080b' },
  empty: { sky0: '#020205', horizon: '#6a5a66', seam: '#3a1446', warm: '#ffb25e', screen: '#cfefff' },
  lift: { sky0: '#0a0514', sky1: '#1f0b2a', horizon: '#3a1446', gold: '#ffc46b', rose: '#ff6fa0', ring: '#ff9fc3', friend: '#ffd9a8', ground: '#09040f' },
  blaze: { sky0: '#06070a', back: '#e8f6ff', backHi: '#ffffff', screen: '#ddf4ff', warm: '#ffc46b', rose: '#ff6fa0', figure: '#000000', frost: '#d6e6ee', ground: '#040506' },
  home: { sky0: '#000000', light: '#ffcf8a', halo: '#ff9a5c' },
};

function mean(col, a, b) {
  let s = 0, n = 0;
  for (let i = Math.max(0, a); i < Math.min(col.length, b); i++) { s += col[i]; n++; }
  return n ? s / n : 0;
}

/** Role of each section from its arrangement and loudness. */
export function sectionRoles(motion) {
  const { fps, columns: c, events: ev } = motion;
  const secs = ev.sections || [];
  const louds = secs.map((s) => mean(c.loud, Math.ceil(s.t0 * fps), Math.floor(s.t1 * fps)));
  const sorted = [...louds].sort((a, b) => a - b);
  const median = sorted[Math.floor(sorted.length / 2)] ?? 0;
  const maxLoud = Math.max(...louds, 0);
  return secs.map((s, k) => {
    const a = Math.ceil(s.t0 * fps), b = Math.floor(s.t1 * fps);
    const drums = mean(c.drums_active, a, b);
    const voice = mean(c.voc_active, a, b);
    const last = k === secs.length - 1;
    let scene;
    if (k === 0 && drums < 0.2) scene = 'memories';
    else if (last && (louds[k] < median || voice < 0.3)) scene = 'ember';
    else if (drums < 0.2 && (voice < 0.5 || louds[k] < median)) scene = 'void';
    else if (drums >= 0.2 && louds[k] >= median) scene = 'crowd';
    else scene = 'orbit';
    return { label: s.label, t0: s.t0, t1: s.t1, scene, loud: louds[k], drums, voice, loudest: louds[k] === maxLoud };
  });
}

export function autoTreatment(motion) {
  const roles = sectionRoles(motion);
  const ev = motion.events;
  const timeline = [];
  let crowdCount = 0;
  roles.forEach((r, k) => {
    const prev = timeline[timeline.length - 1];
    if (prev && prev.scene === r.scene) { prev.t1 = k === roles.length - 1 ? '@end' : r.t1; return; }
    const id = `${r.scene}_${r.label}`.toLowerCase();
    const e = { id, scene: r.scene, t0: k === 0 ? 0 : r.t0, t1: k === roles.length - 1 ? '@end' : r.t1, params: {}, post: {} };
    if (r.scene === 'memories') e.palette = 'night';
    if (r.scene === 'crowd') {
      e.palette = r.loudest || crowdCount > 0 ? 'blaze' : 'screens';
      e.params = { variant: e.palette === 'blaze' ? 'blaze' : 'dusk', count: e.palette === 'blaze' ? 1300 : 560, numbGain: e.palette === 'blaze' ? 1 : 0.8 };
      e.post = { frost: e.params.numbGain };
      crowdCount++;
    }
    if (r.scene === 'void') e.palette = 'empty';
    if (r.scene === 'orbit') e.palette = 'lift';
    if (r.scene === 'ember') e.palette = 'home';
    timeline.push(e);
  });
  const transitions = [{ type: 'fade_from_black', t: 0, dur: 0.3 }];
  (ev.cuts || []).forEach((_, k) => transitions.push({ type: 'cut', t: `@cuts[${k}]`, dur: 0.1 }));
  (ev.key_changes || []).forEach((_, k) => transitions.push({ type: 'flash', t: `@key_changes[${k}].t`, dur: 0.5, params: { peak: 0.25, tau: 0.18 } }));
  const title = motion.meta && motion.meta.title
    ? { text: [motion.meta.title.replace(/\s*[([][^)\]]*[)\]]\s*$/, '').split(' - ')[0], (motion.meta.artist || '').replace(/official$/i, '')].filter(Boolean).join(' · '),
        t0: 1.0, t1: 5.5, fadeIn: 0.5, fadeOut: 0.9, x: 96, y: 1000, size: 30, tracking: 0.3, color: '#f4e9dc', alpha: 0.7, font: 'Inter Light' }
    : null;
  return {
    song: 'auto', notes: 'Generated by treatments/auto.mjs from section roles.',
    global: { degPerSemi: 30, seed: 1 }, title,
    palettes: BASE,
    post: { bloom: 0.35, bloomRadius: 28, vignette: 0.35, grain: 0.05, frost: 0, frostTint: '#bfd4dc' },
    timeline, transitions,
  };
}
